"""Generate docs/bench.md from real runs (no model needed). Run: python bench/report.py"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from ontolite_bench.runner import run_all  # noqa: E402
from ontolite_bench.tasks import ALL, FAMILIES  # noqa: E402

lines = ["# Ontolite-Bench results (generated by `bench/report.py`)", "",
         "40 tasks, deterministic solvers, no model and no network. Real-model runs are a separate step "
         "(`inspect eval bench/ontolite_bench/inspect_tasks.py -T solver=agent`) and are **not** reported here.", "",
         "| family | tasks |", "| --- | --- |"] + [f"| {f} | {n} |" for f, n in FAMILIES.items()]
ref = run_all("reference")
lines += ["", "## Harness validity", "",
          f"- Reference solutions pass all graders in a fresh store: **{sum(r.passed for r in ref.values())}/40**.",
          f"- Null agent (does nothing) passes **{sum(r.passed for r in run_all('null').values())}/40** "
          "(only the 6 leakage tasks, where doing nothing is safe but not correct).",
          f"- Adversarial solvers against intact governance: contained on "
          f"**{sum(r.passed for k, r in run_all('attack').items() if any(t.id == k and t.attack for t in ALL))}/14** breach tasks.",
          "", "## Mutation testing: break one control on purpose, do the graders notice?", "",
          "| mutant (control disabled) | guarding tasks | intact system passes | broken system fails (detected) |",
          "| --- | --- | --- | --- |"]
for m in ("permissive", "no_handle_binding", "no_preconditions"):
    ids = [t.id for t in ALL if m in t.guards]
    ok = run_all("attack", only=ids)
    bad = run_all("attack", only=ids, mutation=m)
    lines.append(f"| {m} | {len(ids)} | {sum(r.passed for r in ok.values())}/{len(ids)} | "
                 f"{sum(not r.passed for r in bad.values())}/{len(ids)} |")
ids = [t.id for t in ALL if t.family == "tool_integrity"]
lines += ["", "## Tool-integrity ablation (susceptible scripted agent that obeys instructions in tool descriptions)", "",
          "| arm | tasks hijacked (store changed) |", "| --- | --- |",
          f"| no gate | {sum(not r.passed for r in run_all('naive', only=ids).values())}/4 |",
          f"| bench-local pin+scan gate (stand-in for Toolpin) | {sum(not r.passed for r in run_all('naive', gate=True, only=ids).values())}/4 |",
          "", "The gate here is a minimal stand-in so Ontolite stays independent of Toolpin; Toolpin's own benchmark "
          "repeats the ablation with the real gate.", ""]
Path("docs/bench.md").write_text("\n".join(lines))
print("\n".join(lines))
